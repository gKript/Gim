#ifndef _GIM_HTML_OBJ_H_
#define _GIM_HTML_OBJ_H_

	#include "gim_base_header.h"
	#include "gim_string.h"
	#include "gim_file.h"

	#define	 GIM_HTML_INDENT_WIDTH	4		/*!<	spaces for each indent level */


	/*!	\struct		gim_html_page
		\warning	\n <b>It is not possible to use directly this struct.</b>
		\internal
		\brief		This struct is used by Gim to make an html page.
	*/
	struct gim_html_page {
		char			title[512];
		char			comment[512];
		char			file_name[2048];
		_gim_handler	* fh;			/*!<	NULL when no page is open */
	};


	/*! \class 		gim_html_obj
		\brief		The Gim's html obj is useful to easily make web pages from c++ code. \n
					All the text passed to Export_text and Export_with_tag_text is escaped
					( &lt; &gt; &amp; &quot; &#39; ), so values coming from sensors or users
					cannot break the page. The raw methods ( Export, Export_with_tag, ... ) write
					the string as it is: use them only with trusted HTML. \n
					Example: \code
		#include <gim/gim.h>

		int main ( int argc , char *argv[] ) {
			gim_obj * gim = new gim_obj;
			_gim_html * page = new _gim_html;
			page->new_page( "First page" , "generated by Gim" , "./test_page.html" );
			page->Export_tag_open( "h1" );
			page->Export_text( "Temperature <b>&</b> humidity" );
			page->Export_tag_close( "h1" );
			page->Export_with_tag_text( "p" , gim_version() );
			page->close_page();
			delete page;
			delete gim;
			return 0;
		}
					\endcode
		\author		Danilo Zannoni  -  asyntote@gkript.org
		\version	2.1-0
		\date		2003-2026
	*/
	class gim_html_obj {
		public:
			/*!	\brief	Creates the file and writes the page header
				( doctype, html, head with charset and escaped title, body ).
				If a page is already open it is closed first.
				\param	title		Page title ( escaped )
				\param	comment		Comment written in the head as an HTML comment ( may be NULL )
				\param	file_name	Output file
				\return	\a __GIM_OK on success, \a __GIM_ERROR on fail
			*/
			_gim_flag	new_page				( const char * title , const char * comment , const char * file_name );

			/*!	\brief	Closes body and html, then closes the file. Safe to call more than once.
				\return	\a __GIM_OK on success , \a __GIM_NOT_OK if no page is open
			*/
			_gim_flag	close_page				( void );

			/*!	\brief	Writes a raw line of HTML ( not escaped ).
			*/
			_gim_flag	Export					( const char * to_export );

			/*!	\brief	Writes a line with an empty tag, e.g. "hr" or "meta charset=..." ( raw ).
			*/
			_gim_flag	Export_tag				( const char * tag );

			/*!	\brief	Writes an opening tag and increases the indent level. \a tag may contain attributes.
			*/
			_gim_flag	Export_tag_open			( const char * tag );

			/*!	\brief	Decreases the indent level and writes the closing tag. Only the tag name is used,
						so the attributes given to Export_tag_open are not repeated.
			*/
			_gim_flag	Export_tag_close		( const char * tag );

			/*!	\brief	Writes <tag>to_export</tag> on one line, to_export is raw HTML.
			*/
			_gim_flag	Export_with_tag			( const char * tag , const char * to_export );

			/*!	\brief	Writes escaped text on its own line.
			*/
			_gim_flag	Export_text				( const char * text );

			/*!	\brief	Writes <tag>text</tag> on one line, text is escaped.
			*/
			_gim_flag	Export_with_tag_text	( const char * tag , const char * text );

			/*!	\brief	\a __GIM_OK if a page is open for writing, \a __GIM_NOT_OK otherwise.
			*/
			_gim_flag	is_open					( void );

		private:
			gim_html_obj				( const gim_html_obj & );		/* not copyable: owns a page */
			gim_html_obj & operator=	( const gim_html_obj & );

			_gim_flag	check_open				( const char * caller );
			_gim_flag	check_tag				( const char * tag );
			void		make_indent				( void );
			void		write_escaped			( const char * text );
			void		write_comment			( const char * comment );
			void		write_open_tag			( const char * tag );
			void		write_close_tag			( const char * tag );

			gim_html_page		* page;
			int					indent_level;

		public:
			inline gim_html_obj() {
				gim_error->set( "gim_html_obj::gim_html_obj" , "page initialization start" );
				indent_level = 0;
				page = (gim_html_page *)gim_memory->Alloc( sizeof( gim_html_page )  , __GIM_HTML_PAGE , __GIM_HIDE );
				if ( page == NULL ) {
					gim_error->set( GIM_ERROR_CRITICAL , "gim_html_obj::gim_html_obj" , "    Memory NOT CORRECTLY allocated succesfully" , __GIM_ERROR );
				}
				else {
					page->fh = NULL;
					page->title[0] = page->comment[0] = page->file_name[0] = '\0';
					gim_error->set( "gim_html_obj::gim_html_obj" , "    Costructor correctly finish his job" );
				}
			};

			inline ~gim_html_obj() {
				gim_error->set( "gim_html_obj::~gim_html_obj" , "Destructor start" );
				if ( page != NULL ) {
					if ( page->fh != NULL ) {
						gim_error->set( "gim_html_obj::~gim_html_obj" , "    Closing page on destruct" );
						close_page();
					}
					gim_memory->Free( page );
					page = NULL;
				}
			};
	};

#endif // _GIM_HTML_OBJ_H_
